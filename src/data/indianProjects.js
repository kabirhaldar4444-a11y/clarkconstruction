// Helper functions for easy filtering, querying, and reporting
export function getIndianProjectsByCategory(category) {
  if (!category || category === 'All') return INDIAN_PROJECTS;
  return INDIAN_PROJECTS.filter((p) => p.category === category);
}

export function getIndianProjectsByState(state) {
  if (!state) return INDIAN_PROJECTS;
  const target = state.toLowerCase();
  return INDIAN_PROJECTS.filter((p) => 
    p.state.toLowerCase().includes(target) || 
    p.location.toLowerCase().includes(target)
  );
}

export function searchIndianProjects(query) {
  if (!query) return INDIAN_PROJECTS;
  const q = query.toLowerCase().trim();
  return INDIAN_PROJECTS.filter((p) =>
    p.title.toLowerCase().includes(q) ||
    p.location.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.client.toLowerCase().includes(q) ||
    p.specs.toLowerCase().includes(q) ||
    p.summary.toLowerCase().includes(q)
  );
}

